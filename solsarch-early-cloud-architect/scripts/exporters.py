#!/usr/bin/env python3
"""Export the architecture in the formats other tools read, so SolsArch feeds them instead of competing with them.

    Structurizr DSL     architecture.dsl           (Structurizr, IcePanel imports through C4 tooling)
    PlantUML C4         architecture.puml          (any PlantUML renderer)
    LikeC4              architecture.c4            (LikeC4 CLI and editor)
    draw.io             architecture.drawio        (diagrams.net, Confluence, Lucid import)
    Backstage           catalog-info.yaml          (components, resources, systems, with the maturity level as an annotation)
    Score               score/<unit>.score.yaml    (Humanitec Platform Orchestrator workload specification)
    Port                port-entities.json         (entities to import into Port)

All of them are written from the same plan, design and scorecard, so they agree with the report. Nothing is invented: a box
exists only because a unit was detected or a plan decision asked for it.
"""
import json
import re
from xmltext import escape

from iac_common import Files, slug
from iac_k8s import dump

DATA_KEYS = ("database", "database_mysql", "database_mongo", "cache", "queue_kafka", "queue_rabbitmq", "storage", "vector", "search")


def ident(text):
    return re.sub(r"[^A-Za-z0-9_]", "_", str(text)).strip("_") or "x"


class Model:
    def __init__(self, plan, design, scan, scorecard=None, project=None):
        self.plan, self.design, self.scan, self.card = plan, design, scan, scorecard
        self.project = project or plan.get("project") or "system"
        self.units = [u for u in design["units"]]
        self.decisions = {d["key"]: d for d in plan["decisions"]}
        self.data = [d for d in plan["decisions"] if d["key"] in DATA_KEYS and d["key"] != "vector"]
        self.external = plan.get("external_services", [])
        self.edges = self.relations()

    def tech(self, u):
        return ", ".join(u.get("frameworks") or u.get("languages") or []) or u["kind"]

    def relations(self):
        edges = []
        units = [u for u in self.units if u["kind"] != "static"]
        web = [u for u in units if u["kind"] == "web"]
        api = [u for u in units if u["kind"] in ("api", "service")]
        for w in web:
            for a in api:
                edges.append((w["name"], a["name"], "Calls the API over HTTPS"))
        for u in units:
            for key in u.get("uses", []):
                d = self.decisions.get(key)
                if d and key in DATA_KEYS and key != "vector":
                    verb = {"cache": "Caches data in", "queue_kafka": "Publishes and consumes events on", "queue_rabbitmq": "Publishes and consumes messages on",
                            "storage": "Stores files in"}.get(key, "Reads and writes")
                    edges.append((u["name"], key, "%s %s" % (verb, d["short"])))
        for ext in self.external:
            for u in api[:1] or units[:1]:
                edges.append((u["name"], "ext_" + ext["key"], "Calls %s" % ext["name"]))
        return edges

    def node_label(self, key):
        if key.startswith("ext_"):
            return next((e["name"] for e in self.external if "ext_" + e["key"] == key), key)
        if key in self.decisions:
            return self.decisions[key]["service"]
        return key


# --------------------------------------------------------------------------- Structurizr
def structurizr(m):
    lines = ['workspace "%s" "Generated by SolsArch Early Cloud Architect" {' % m.project, "", "  model {", '    user = person "User" "A person using the application"',
             '    system = softwareSystem "%s" "%s" {' % (m.project, m.plan["cloud_name"])]
    for u in m.units:
        if u["kind"] == "static":
            continue
        lines.append('      %s = container "%s" "%s" "%s"' % (ident(u["name"]), u["name"], u["kind"], m.tech(u)))
    for d in m.data:
        lines.append('      %s = container "%s" "%s" "%s" "Database"' % (ident(d["key"]), d["short"], d["role"], d["service"]))
    lines.append("    }")
    for e in m.external:
        lines.append('    ext_%s = softwareSystem "%s" "External service" "External"' % (ident(e["key"]), e["name"]))
    front = next((u for u in m.units if u["kind"] in ("web", "static")), None) or (m.units[0] if m.units else None)
    if front and front["kind"] != "static":
        lines.append('    user -> %s "Uses"' % ident(front["name"]))
    for a, b, text in m.edges:
        lines.append('    %s -> %s "%s"' % (ident(a) if not b.startswith("ext_") else ident(a), ident(b), text.replace('"', "'")))
    lines += ["  }", "", "  views {", "    systemContext system \"context\" {", "      include *", "      autolayout lr", "    }",
              "    container system \"containers\" {", "      include *", "      autolayout lr", "    }", "  }", "}"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- PlantUML C4
def plantuml(m):
    lines = ["@startuml", "!include https://raw.githubusercontent.com/plantuml-stdlib/C4-PlantUML/master/C4_Container.puml", "",
             'title %s on %s' % (m.project, m.plan["cloud_name"]), "", 'Person(user, "User", "Uses the application")',
             'System_Boundary(system, "%s") {' % m.project]
    for u in m.units:
        if u["kind"] != "static":
            lines.append('  Container(%s, "%s", "%s", "%s")' % (ident(u["name"]), u["name"], m.tech(u), u["kind"]))
    for d in m.data:
        lines.append('  ContainerDb(%s, "%s", "%s", "%s")' % (ident(d["key"]), d["short"], d["service"], d["role"]))
    lines.append("}")
    for e in m.external:
        lines.append('System_Ext(ext_%s, "%s", "External service")' % (ident(e["key"]), e["name"]))
    front = next((u for u in m.units if u["kind"] == "web"), None) or next((u for u in m.units if u["kind"] != "static"), None)
    if front:
        lines.append('Rel(user, %s, "Uses", "HTTPS")' % ident(front["name"]))
    for a, b, text in m.edges:
        lines.append('Rel(%s, %s, "%s")' % (ident(a), ident(b), text.replace('"', "'")))
    lines += ["", "@enduml"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- LikeC4
def likec4(m):
    lines = ["specification {", "  element person", "  element system", "  element container", "  element database", "  element external", "}", "", "model {",
             "  user = person 'User' {", "    description 'Uses the application'", "  }", "  system = system '%s' {" % m.project]
    for u in m.units:
        if u["kind"] != "static":
            lines += ["    %s = container '%s' {" % (ident(u["name"]), u["name"]), "      technology '%s'" % m.tech(u).replace("'", ""), "    }"]
    for d in m.data:
        lines += ["    %s = database '%s' {" % (ident(d["key"]), d["short"].replace("'", "")), "      technology '%s'" % d["service"].replace("'", ""), "    }"]
    lines.append("  }")
    for e in m.external:
        lines.append("  ext_%s = external '%s'" % (ident(e["key"]), e["name"].replace("'", "")))
    front = next((u for u in m.units if u["kind"] == "web"), None) or next((u for u in m.units if u["kind"] != "static"), None)
    if front:
        lines.append("  user -> system.%s 'Uses'" % ident(front["name"]))
    for a, b, text in m.edges:
        target = "ext_" + ident(b[4:]) if b.startswith("ext_") else "system." + ident(b)
        lines.append("  system.%s -> %s '%s'" % (ident(a), target, text.replace("'", "")))
    lines += ["}", "", "views {", "  view index {", "    include *", "  }", "  view containers of system {", "    include *", "  }", "}"]
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- draw.io
def drawio(m):
    boxes, ids = [], {}
    x, y = 40, 40

    def add(key, label, kind, col, row):
        cid = "n%d" % (len(ids) + 2)
        ids[key] = cid
        fill = {"unit": "#dae8fc", "data": "#d5e8d4", "ext": "#f5f5f5", "user": "#fff2cc"}[kind]
        boxes.append('<mxCell id="%s" value="%s" style="rounded=1;whiteSpace=wrap;html=1;fillColor=%s;strokeColor=#333333;" vertex="1" parent="1">'
                     '<mxGeometry x="%d" y="%d" width="180" height="70" as="geometry"/></mxCell>' % (cid, escape(label, {'"': "&quot;"}), fill, 40 + col * 240, 40 + row * 130))

    add("user", "User", "user", 0, 0)
    units = [u for u in m.units if u["kind"] != "static"]
    for i, u in enumerate(units):
        add(u["name"], "%s (%s)\n%s" % (u["name"], u["kind"], m.tech(u)), "unit", i, 1)
    for i, d in enumerate(m.data):
        add(d["key"], "%s\n%s" % (d["short"], d["service"]), "data", i, 2)
    for i, e in enumerate(m.external):
        add("ext_" + e["key"], e["name"], "ext", i, 3)
    edges = []
    front = next((u for u in units if u["kind"] == "web"), None) or (units[0] if units else None)
    pairs = ([("user", front["name"], "Uses")] if front else []) + [(a, b, t) for a, b, t in m.edges]
    for n, (a, b, t) in enumerate(pairs):
        if a in ids and b in ids:
            edges.append('<mxCell id="e%d" value="%s" style="endArrow=classic;html=1;" edge="1" parent="1" source="%s" target="%s"><mxGeometry relative="1" as="geometry"/></mxCell>'
                         % (n, escape(t, {'"': "&quot;"}), ids[a], ids[b]))
    body = "".join(boxes + edges)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<mxfile host="solsarch"><diagram name="%s" id="solsarch"><mxGraphModel dx="1000" dy="600" grid="1" gridSize="10" page="1" pageWidth="1169" pageHeight="827">'
            '<root><mxCell id="0"/><mxCell id="1" parent="0"/>%s</root></mxGraphModel></diagram></mxfile>\n' % (escape(m.project), body))


# --------------------------------------------------------------------------- Backstage
def backstage(m):
    docs = []
    level = m.card["overall_level"] if m.card else None
    label = m.card["overall_label"] if m.card else None
    annotations = {"solsarch.io/plan-fingerprint": m.plan["fingerprint"], "solsarch.io/cloud": m.plan["cloud"]}
    if level is not None:
        annotations["solsarch.io/ops-maturity-level"] = str(level)
        annotations["solsarch.io/ops-maturity-label"] = label
    docs.append({"apiVersion": "backstage.io/v1alpha1", "kind": "System", "metadata": {"name": slug(m.project), "description": "Architecture from SolsArch on %s" % m.plan["cloud_name"],
                                                                                    "annotations": annotations}, "spec": {"owner": "REPLACE-with-your-team"}})
    for u in m.units:
        if u["kind"] == "static":
            continue
        spec = {"type": "service" if u["kind"] != "web" else "website", "lifecycle": "production", "owner": "REPLACE-with-your-team", "system": slug(m.project)}
        deps = ["resource:%s" % slug(b) for a, b, t in m.edges if a == u["name"] and not b.startswith("ext_")]
        if deps:
            spec["dependsOn"] = deps
        docs.append({"apiVersion": "backstage.io/v1alpha1", "kind": "Component",
                     "metadata": {"name": slug(u["name"]), "description": "%s unit (%s)" % (u["kind"], m.tech(u)),
                                  "annotations": dict(annotations, **({"solsarch.io/health-path": u["health_path"]} if u.get("health_path") else {})),
                                  "tags": [slug(x) for x in (u.get("languages") or [])][:4]}, "spec": spec})
    for d in m.data:
        docs.append({"apiVersion": "backstage.io/v1alpha1", "kind": "Resource", "metadata": {"name": slug(d["key"]), "description": "%s (%s)" % (d["role"], d["service"])},
                     "spec": {"type": d["category"].lower().replace(" ", "-"), "owner": "REPLACE-with-your-team", "system": slug(m.project)}})
    return "---\n".join(dump(x) for x in docs)


# --------------------------------------------------------------------------- Score (Humanitec)
def score(m):
    out = {}
    for u in m.units:
        if u["kind"] == "static":
            continue
        res = {}
        for key in u.get("uses", []):
            d = m.decisions.get(key)
            if not d or key == "vector":
                continue
            kind = {"database": "postgres", "database_mysql": "mysql", "database_mongo": "mongodb", "cache": "redis", "queue_kafka": "kafka",
                    "queue_rabbitmq": "amqp", "storage": "s3", "search": "elasticsearch"}.get(key)
            if kind:
                res[ident(key)] = {"type": kind}
        variables = {}
        for rk, v in res.items():
            name = "DATABASE_URL" if rk in ("database", "database_mysql", "database_mongo") else rk.upper() + "_URL"
            variables[name] = "${resources.%s.%s}" % (rk, "bucket" if v["type"] == "s3" else "uri")
        container = {"image": ".", "variables": variables}
        spec = {"apiVersion": "score.dev/v1b1", "metadata": {"name": slug(u["name"])}, "containers": {"main": container}}
        if u["port"]:
            spec["service"] = {"ports": {"web": {"port": 80, "targetPort": u["port"]}}}
            container["livenessProbe"] = {"httpGet": {"path": u.get("health_path") or "/", "port": u["port"]}}
        if res:
            spec["resources"] = res
        if u["kind"] in ("web", "api") and u["port"]:
            spec.setdefault("resources", {})["dns"] = {"type": "dns"}
            spec["resources"]["route"] = {"type": "route", "params": {"host": "${resources.dns.host}", "path": "/", "port": 80}}
        out["score/%s.score.yaml" % slug(u["name"])] = dump(spec)
    return out


# --------------------------------------------------------------------------- Port
def port(m):
    entities = [{"blueprint": "service", "identifier": slug(u["name"]), "title": u["name"],
                 "properties": {"kind": u["kind"], "technology": m.tech(u), "port": u["port"], "healthPath": u.get("health_path"),
                                "opsMaturityLevel": m.card["overall_level"] if m.card else None, "cloud": m.plan["cloud"]}}
                for u in m.units if u["kind"] != "static"]
    entities += [{"blueprint": "resource", "identifier": slug(d["key"]), "title": d["short"], "properties": {"service": d["service"], "role": d["role"]}} for d in m.data]
    return json.dumps({"entities": entities}, indent=2) + "\n"


FORMATS = ("structurizr", "plantuml", "likec4", "drawio", "backstage", "score", "port")


def generate(plan, design, scan, scorecard=None, project=None):
    m = Model(plan, design, scan, scorecard, project)
    files = Files(plan["fingerprint"])
    files.add("exports/architecture.dsl", structurizr(m), header=False)
    files.add("exports/architecture.puml", plantuml(m), header=False)
    files.add("exports/architecture.c4", likec4(m), header=False)
    files.add("exports/architecture.drawio", drawio(m), header=False)
    files.add("exports/backstage/catalog-info.yaml", backstage(m))
    for path, text in score(m).items():
        files.add("exports/" + path, text)
    files.add("exports/port-entities.json", port(m))
    files.add("exports/README.md", "\n".join([
        "# Architecture exports", "",
        "The same architecture as the report, written for other tools. Import what you use and ignore the rest.", "",
        "| File | Opens in |", "|---|---|",
        "| `architecture.dsl` | Structurizr (workspace DSL) |", "| `architecture.puml` | PlantUML with C4-PlantUML |", "| `architecture.c4` | LikeC4 |",
        "| `architecture.drawio` | diagrams.net / draw.io, Confluence, Lucid import |", "| `backstage/catalog-info.yaml` | Backstage software catalog (copy to the repository root) |",
        "| `score/*.score.yaml` | Humanitec Platform Orchestrator (Score workload specs) |", "| `port-entities.json` | Port (import as entities of your `service` and `resource` blueprints) |", "",
        "Replace the `REPLACE-with-your-team` owner in the Backstage file.", ""]))
    return files

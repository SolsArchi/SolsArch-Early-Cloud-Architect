#!/usr/bin/env python3
"""Shared pieces for every infrastructure-code generator: the model, the file set and canonical HCL formatting.

Standard library only. The generators turn the plan, the design review and the profile into files. They never invent a
service: a resource appears only because a decision in the plan asked for it, and every file starts with a
header that says which plan produced it.
"""
import re
import textwrap

TOOL = "SolsArch Early Cloud Architect"
LINK = "https://github.com/SolsArchi/SolsArch-Early-Cloud-Architect"
HEADER_LINE = "Generated by %s (plan %s). Review before you apply. %s"
COMMENT_STYLE = {".tf": "#", ".tfvars": "#", ".hcl": "#", ".yml": "#", ".yaml": "#", ".ini": "#", ".cfg": "#", ".sh": "#",
                 ".toml": "#", ".example": "#", ".md": None, ".json": None, ".txt": "#", ".tpl": "#", ".j2": "#", ".cfg.j2": "#"}
NAMELESS = {"Dockerfile": "#", "Procfile": "#", ".gitignore": "#", ".dockerignore": "#", "Caddyfile": "#"}


def slug(text, fallback="app"):
    text = re.sub(r"[^a-z0-9]+", "-", str(text or "").lower()).strip("-")
    return (text or fallback)[:40].strip("-") or fallback


def ident(text, fallback="x"):
    """A valid HCL identifier."""
    text = re.sub(r"[^a-z0-9_]+", "_", str(text or "").lower()).strip("_")
    if not text or text[0].isdigit():
        text = fallback + "_" + text
    return text


def q(text):
    """A double-quoted HCL or JSON string."""
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"').replace("${", "$${").replace("%{", "%%{") + '"'


class Model:
    """What every generator needs, read once from the plan, the design review, the profile and the scan."""

    def __init__(self, plan, design, profile, scan, project=None):
        self.plan, self.design, self.profile, self.scan = plan, design, profile, scan
        self.cloud = plan["cloud"]
        self.mode = plan["compute_model"]
        self.fingerprint = plan["fingerprint"]
        self.all_by_key = {d["key"]: d for d in plan["decisions"]}
        # Only services that live in this provider's account are built here. A decision that another provider supplies (a free
        # MongoDB Atlas cluster chosen with --also, say) has its own module, and the application reads its address from a variable.
        self.by_key = {k: d for k, d in self.all_by_key.items() if d.get("provider", self.cloud) == self.cloud}
        self.external_decisions = [d for k, d in self.all_by_key.items() if k not in self.by_key]
        self.project = slug(project or plan.get("project") or "app")
        self.units = [u for u in design["units"] if u["kind"] in ("api", "web", "worker", "service", "static")]
        if not self.units:
            self.units = [{"name": "app", "kind": "service", "folder": ".", "port": 8080, "health_path": "/", "health_source": "default",
                           "frameworks": [], "languages": [], "dockerfile": None, "runs_as_root": False, "uses": [], "evidence": []}]
        self.app_units = [u for u in self.units if u["kind"] in ("api", "web", "service")]
        self.web_units = [u for u in self.units if u["kind"] in ("api", "web", "service")]
        self.workers = [u for u in self.units if u["kind"] == "worker"]
        self.static_units = [u for u in self.units if u["kind"] == "static"]
        cap = design["capacity"]
        self.cap = cap
        self.sizing = cap["sizing"]
        self.single_az = design["single_az"]
        self.lean = design["lean"]
        self.compliance = list(profile.get("compliance") or [])
        self.regulated = bool({"hipaa", "pci-dss", "soc2", "fedramp", "iso27001"} & set(self.compliance))
        self.streaming = (scan.get("signals") or {}).get("streaming", "none") != "none"
        self.region = profile.get("region")
        self.has = lambda key: key in self.by_key
        self.db_key = "database" if "database" in self.by_key else ("database_mysql" if "database_mysql" in self.by_key else None)
        self.external = plan.get("external_services", [])
        self.config_inputs = plan.get("config_inputs", [])
        self.scheduled = any(u.get("scheduler") for u in self.units)
        self.streaming_units = [u for u in self.units if u.get("streaming")]
        self.gaps = plan.get("gaps", [])
        self.domains = []

    @property
    def needs_private_network(self):
        """True when something must sit in a private network in this account: always-on containers, or data stores kept here."""
        data_here = any(d.get("layer") == "data" for d in self.by_key.values())
        return self.mode == "server" or data_here or "network" in self.by_key

    @property
    def direct_ingress(self):
        """True when public traffic reaches the functions or services at the platform's own HTTPS address, with no gateway in front."""
        return (self.by_key.get("ingress") or {}).get("need") == "ingress_function_url"

    @property
    def settings(self):
        """Every environment variable the code reads: [{name, required, category}], sorted by name."""
        return sorted(({"name": i["name"], "required": bool(i["required"]), "category": i["category"]} for i in self.config_inputs), key=lambda i: i["name"])

    @property
    def required_settings(self):
        """Names the app cannot start without: marked required in the code, or the connection to a database another provider hosts."""
        external = {d["key"] for d in self.external_decisions}
        names = set()
        for i in self.settings:
            n = i["name"]
            if i["required"]:
                names.add(n)
            elif "database_mongo" in external and "MONGO" in n and i["category"] == "connection":
                names.add(n)
            elif "database" in external and ("DATABASE_URL" in n or "POSTGRES" in n):
                names.add(n)
        return sorted(names)

    @property
    def replicas(self):
        return self.sizing["replicas_per_unit"]

    def vcpu_mem(self):
        """CPU and memory per task in the units the providers use (CPU units and MiB)."""
        v = self.sizing["unit_vcpu"]
        return int(v * 1024), int(self.sizing["unit_memory_gb"] * 1024)

    def public_units(self):
        """Units that receive traffic from the internet, in a fixed order: web first, then api, then service."""
        order = {"web": 0, "api": 1, "service": 2}
        return sorted([u for u in self.units if u["kind"] in order], key=lambda u: (order[u["kind"]], u["name"]))


def selfrun(model, key):
    """True when the plan says this service runs in a container on your own server, not as a managed service."""
    d = model.by_key.get(key)
    if not d:
        return False
    return "container" in (d.get("service") or "").lower() or (d.get("short") or "").lower().startswith("self-run")


class Files:
    """The generated files of one run, keyed by their path inside the output folder."""

    def __init__(self, plan_fingerprint):
        self.files = {}
        self.fingerprint = plan_fingerprint

    def add(self, path, text, header=True):
        text = text.replace("\r\n", "\n")
        if not text.endswith("\n"):
            text += "\n"
        if header:
            text = stamp(path, text, self.fingerprint)
        self.files[path] = text
        return path

    def update(self, other):
        self.files.update(other.files)

    def __iter__(self):
        return iter(sorted(self.files))


def stamp(path, text, fingerprint):
    """Put the SolsArch header comment at the top of a file whose format allows comments."""
    name = path.rsplit("/", 1)[-1]
    ext = "." + name.rsplit(".", 1)[-1] if "." in name else ""
    comment = NAMELESS.get(name) or COMMENT_STYLE.get(ext)
    if name.endswith(".md"):
        return "<!-- " + HEADER_LINE % (TOOL, fingerprint, LINK) + " -->" + chr(10) + chr(10) + text
    if comment is None:
        return text
    line = comment + " " + HEADER_LINE % (TOOL, fingerprint, LINK)
    first = text.split(chr(10), 1)[0]
    if first.startswith("#!") or first.startswith("---"):
        head, _, rest = text.partition(chr(10))
        if first.startswith("---"):
            return head + chr(10) + line + chr(10) + rest
        return head + chr(10) + line + chr(10) + rest
    return line + chr(10) + text


# ------------------------------------------------------------------ HCL format
_ATTR = re.compile(r"^(\s*)([A-Za-z_][\w-]*)(\s*)=(\s*)(.*)$")


def _bracket_delta(line):
    """(opens, closes, starts_with_closer) for a line, ignoring brackets inside strings and comments."""
    opens = closes = 0
    quote = False
    j = 0
    stripped = line.strip()
    while j < len(stripped):
        ch = stripped[j]
        if quote:
            if ch == "\\":
                j += 2
                continue
            if ch == '"':
                quote = False
        else:
            if ch == '"':
                quote = True
            elif ch == "#" or (ch == "/" and stripped[j:j + 2] == "//"):
                break
            elif ch in "([{":
                opens += 1
            elif ch in ")]}":
                closes += 1
        j += 1
    return opens, closes, bool(stripped) and stripped[0] in ")]}"


def reindent(text, unit="  "):
    """Indent by nesting depth. One line opens or closes at most one level, as terraform fmt does."""
    out, level, heredoc = [], 0, None
    for line in text.split(chr(10)):
        if heredoc:
            out.append(line)
            if line.strip() == heredoc:
                heredoc = None
            continue
        stripped = line.strip()
        if not stripped:
            out.append("")
            continue
        opens, closes, starts_closer = _bracket_delta(stripped)
        own = max(0, level - (1 if starts_closer else 0))
        out.append(unit * own + stripped)
        net = opens - closes
        if net > 0:
            level += 1
        elif net < 0:
            level = max(0, level - 1)
        m = re.search(r"<<-?([A-Z_]+)\s*$", stripped)
        if m:
            heredoc = m.group(1)
    return chr(10).join(out)


def fmt_hcl(text):
    """Canonical HCL: indent by depth, then align the equals signs of consecutive single-line attributes."""
    lines = reindent(text).split(chr(10))
    out, group = [], []

    def flush():
        if not group:
            return
        width = max(len(g[1]) for g in group)
        for indent, name, value in group:
            out.append("%s%s = %s" % (indent, name.ljust(width), value))
        group.clear()

    depth_open = ("{", "[", "(")
    in_heredoc = None
    for line in lines:
        if in_heredoc:
            out.append(line)
            if line.strip() == in_heredoc:
                in_heredoc = None
            continue
        m = _ATTR.match(line)
        stripped = line.strip()
        if m and not stripped.startswith(("#", "//")):
            value = m.group(5)
            heredoc = re.match(r"<<-?([A-Z_]+)\s*$", value.strip())
            multi = value.rstrip().endswith(depth_open) or bool(heredoc)
            if multi:
                flush()
                out.append("%s%s = %s" % (m.group(1), m.group(2), value))
                if heredoc:
                    in_heredoc = heredoc.group(1)
                continue
            group.append((m.group(1), m.group(2), value))
            continue
        flush()
        out.append(line)
    flush()
    return chr(10).join(out)


def check_balanced(text, filename="file"):
    """Return a list of problems with unbalanced braces, brackets, parentheses or quotes in HCL text."""
    problems = []
    stack, in_str, i, line_no, heredoc = [], False, 0, 1, None
    pairs = {")": "(", "]": "[", "}": "{"}
    lines = text.split(chr(10))
    for line_no, line in enumerate(lines, 1):
        if heredoc:
            if line.strip() == heredoc:
                heredoc = None
            continue
        m = re.search(r"<<-?([A-Z_]+)\s*$", line)
        stripped = line.split("#", 1)[0] if not in_str else line
        j, quote = 0, False
        while j < len(stripped):
            ch = stripped[j]
            if quote:
                if ch == "\\":
                    j += 2
                    continue
                if ch == '"':
                    quote = False
            else:
                if ch == '"':
                    quote = True
                elif ch in "([{":
                    stack.append((ch, line_no))
                elif ch in ")]}":
                    if not stack or stack[-1][0] != pairs[ch]:
                        problems.append("%s:%d: unexpected %s" % (filename, line_no, ch))
                    else:
                        stack.pop()
            j += 1
        if quote:
            problems.append("%s:%d: unterminated string" % (filename, line_no))
        if m:
            heredoc = m.group(1)
    for ch, n in stack:
        problems.append("%s:%d: %s is never closed" % (filename, n, ch))
    return problems


def T(template, **kw):
    """Fill @@name@@ tokens in a dedented template. An unfilled token is a bug, so it raises."""
    text = textwrap.dedent(template).strip(chr(10)) + chr(10)
    for key, value in kw.items():
        text = text.replace("@@%s@@" % key, str(value))
    if "@@" in text:
        raise ValueError("unfilled template token in: " + text[:80])
    return text


def tf(*parts):
    """Join template parts and format them as canonical HCL."""
    return fmt_hcl(chr(10).join(p.rstrip(chr(10)) + chr(10) for p in parts if p))


def app_env_variable(model):
    """The Terraform variable that carries the app's settings and secrets, with a check that the required ones are present."""
    required = model.required_settings
    validation = ""
    if required:
        validation = chr(10) * 2 + T("""
              validation {
                condition     = alltrue([for k in [@@required@@] : contains(keys(var.app_env), k)])
                error_message = "app_env must contain: @@names@@."
              }
        """, required=", ".join('"%s"' % n for n in required), names=", ".join(required)).rstrip(chr(10))
    return T("""
        variable "app_env" {
          type        = map(string)
          sensitive   = true
          description = "Settings and secrets the application reads from its environment (API keys, connection strings)."
          default     = {}@@validation@@
        }
    """, validation=validation)


def app_env_example(model):
    """tfvars lines that show which keys to fill in. Values are never written."""
    names = sorted(set(model.required_settings) | {i["name"] for i in model.settings if i["category"] != "config"})
    if not names:
        return ""
    lines = ["# Settings and secrets the application reads. Fill these in; do not commit real values.", "# app_env = {"]
    lines += ['#   %s = "REPLACE-me"' % n for n in names] + ["# }"]
    return chr(10).join(lines) + chr(10)


def settings_pairs(model, secrets_apart=False):
    """[(name, hcl_expression)] for every setting the code reads, taken from the app_env variable. With secrets_apart, returns
    (plain, secret) lists so a platform with encrypted variables can keep the two kinds apart."""
    pairs = [(i["name"], 'lookup(var.app_env, "%s", "")' % i["name"], i["category"] != "config") for i in model.settings]
    if secrets_apart:
        return [(n, e) for n, e, sec in pairs if not sec], [(n, e) for n, e, sec in pairs if sec]
    return [(n, e) for n, e, _ in pairs]


def add_app_env_files(files, model):
    """The app_env variable and an example of the keys to fill in, as their own files so any generator can add them."""
    if not model.settings:
        return
    files.add("terraform/app_env.tf", tf(app_env_variable(model)))
    files.add("terraform/app_env.tfvars.example", app_env_example(model), header=False)


def merged_env(model, base):
    """An HCL map of environment variables: the fixed ones, plus every entry of app_env when the code reads settings."""
    return "merge(%s, var.app_env)" % base if model.settings else base

def slug(text, fallback="app"):
    text = re.sub(r"[^a-z0-9]+", "-", str(text or "").lower()).strip("-")
    return (text or fallback)[:40].strip("-") or fallback


def ident(text, fallback="x"):
    """A valid HCL identifier."""
    text = re.sub(r"[^a-z0-9_]+", "_", str(text or "").lower()).strip("_")
    if not text or text[0].isdigit():
        text = fallback + "_" + text
    return text


def q(text):
    """A double-quoted HCL or JSON string."""
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"').replace("${", "$${").replace("%{", "%%{") + '"'


class Model:
    """What every generator needs, read once from the plan, the design review, the profile and the scan."""

    def __init__(self, plan, design, profile, scan, project=None):
        self.plan, self.design, self.profile, self.scan = plan, design, profile, scan
        self.cloud = plan["cloud"]
        self.mode = plan["compute_model"]
        self.fingerprint = plan["fingerprint"]
        self.all_by_key = {d["key"]: d for d in plan["decisions"]}
        # Only services that live in this provider's account are built here. A decision that another provider supplies (a free
        # MongoDB Atlas cluster chosen with --also, say) has its own module, and the application reads its address from a variable.
        self.by_key = {k: d for k, d in self.all_by_key.items() if d.get("provider", self.cloud) == self.cloud}
        self.external_decisions = [d for k, d in self.all_by_key.items() if k not in self.by_key]
        self.project = slug(project or plan.get("project") or "app")
        self.units = [u for u in design["units"] if u["kind"] in ("api", "web", "worker", "service", "static")]
        if not self.units:
            self.units = [{"name": "app", "kind": "service", "folder": ".", "port": 8080, "health_path": "/", "health_source": "default",
                           "frameworks": [], "languages": [], "dockerfile": None, "runs_as_root": False, "uses": [], "evidence": []}]
        self.app_units = [u for u in self.units if u["kind"] in ("api", "web", "service")]
        self.web_units = [u for u in self.units if u["kind"] in ("api", "web", "service")]
        self.workers = [u for u in self.units if u["kind"] == "worker"]
        self.static_units = [u for u in self.units if u["kind"] == "static"]
        cap = design["capacity"]
        self.cap = cap
        self.sizing = cap["sizing"]
        self.single_az = design["single_az"]
        self.lean = design["lean"]
        self.compliance = list(profile.get("compliance") or [])
        self.regulated = bool({"hipaa", "pci-dss", "soc2", "fedramp", "iso27001"} & set(self.compliance))
        self.streaming = (scan.get("signals") or {}).get("streaming", "none") != "none"
        self.region = profile.get("region")
        self.has = lambda key: key in self.by_key
        self.db_key = "database" if "database" in self.by_key else ("database_mysql" if "database_mysql" in self.by_key else None)
        self.external = plan.get("external_services", [])
        self.config_inputs = plan.get("config_inputs", [])
        self.scheduled = any(u.get("scheduler") for u in self.units)
        self.streaming_units = [u for u in self.units if u.get("streaming")]
        self.gaps = plan.get("gaps", [])
        self.domains = []

    @property
    def needs_private_network(self):
        """True when something must sit in a private network in this account: always-on containers, or data stores kept here."""
        data_here = any(d.get("layer") == "data" for d in self.by_key.values())
        return self.mode == "server" or data_here or "network" in self.by_key

    @property
    def direct_ingress(self):
        """True when public traffic reaches the functions or services at the platform's own HTTPS address, with no gateway in front."""
        return (self.by_key.get("ingress") or {}).get("need") == "ingress_function_url"

    @property
    def settings(self):
        """Every environment variable the code reads: [{name, required, category}], sorted by name."""
        return sorted(({"name": i["name"], "required": bool(i["required"]), "category": i["category"]} for i in self.config_inputs), key=lambda i: i["name"])

    @property
    def required_settings(self):
        """Names the app cannot start without: marked required in the code, or the connection to a database another provider hosts."""
        external = {d["key"] for d in self.external_decisions}
        names = set()
        for i in self.settings:
            n = i["name"]
            if i["required"]:
                names.add(n)
            elif "database_mongo" in external and "MONGO" in n and i["category"] == "connection":
                names.add(n)
            elif "database" in external and ("DATABASE_URL" in n or "POSTGRES" in n):
                names.add(n)
        return sorted(names)

    @property
    def replicas(self):
        return self.sizing["replicas_per_unit"]

    def vcpu_mem(self):
        """CPU and memory per task in the units the providers use (CPU units and MiB)."""
        v = self.sizing["unit_vcpu"]
        return int(v * 1024), int(self.sizing["unit_memory_gb"] * 1024)

    def public_units(self):
        """Units that receive traffic from the internet, in a fixed order: web first, then api, then service."""
        order = {"web": 0, "api": 1, "service": 2}
        return sorted([u for u in self.units if u["kind"] in order], key=lambda u: (order[u["kind"]], u["name"]))


def selfrun(model, key):
    """True when the plan says this service runs in a container on your own server, not as a managed service."""
    d = model.by_key.get(key)
    if not d:
        return False
    return "container" in (d.get("service") or "").lower() or (d.get("short") or "").lower().startswith("self-run")



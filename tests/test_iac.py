def build(provider, mode="server", builder=monorepo, profile=None, also=()):
    with tempfile.TemporaryDirectory() as t:
        root = Path(t) / "shop"
        root.mkdir()
        builder(root)
        scan = ast_scanner.scan(root)
        prof = dict(architect.PROFILE_DEFAULTS, **(profile or {}))
        plan = recommend.build_plan(scan, recommend.load_catalog(), provider, mode, list(also), prof)
        design = architect.review(root, scan, plan, prof)
        return plan, design, prof, scan, iac.build(plan, design, prof, scan, "demo")


class EveryProviderGetsFiles(unittest.TestCase):
    def test_every_hosting_provider_builds_in_both_modes(self):
        for provider in providers.hosting_ids():
            for mode in ("server", "serverless"):
                with self.subTest(provider=provider, mode=mode):
                    plan, design, prof, scan, result = build(provider, mode)
                    self.assertGreater(result["manifest"]["file_count"], 5)
                    self.assertTrue(result["manifest"]["next_steps"])
                    for path, text in result["files"].items():
                        self.assertNotIn("@@", text, path)

    def test_terraform_providers_write_the_standard_files(self):
        for provider in TERRAFORM_PROVIDERS:
            with self.subTest(provider=provider):
                _, _, _, _, result = build(provider)
                files = result["files"]
                for name in ("terraform/versions.tf", "terraform/variables.tf", "terraform/outputs.tf", "terraform/README.md",
                             "terraform/terraform.tfvars.example", ".github/workflows/deploy.yml", "docs/ci-setup.md"):
                    self.assertIn(name, files)
                self.assertTrue(any(p.startswith("terraform/backend") for p in files))

    def test_hcl_is_balanced_and_stamped(self):
        for provider in TERRAFORM_PROVIDERS:
            with self.subTest(provider=provider):
                _, _, _, _, result = build(provider, "server", monorepo)
                for path, text in result["files"].items():
                    if path.endswith(".tf"):
                        self.assertEqual(iac_common.check_balanced(text, path), [], path)
                        self.assertIn("Generated by SolsArch Early Cloud Architect", text.splitlines()[0], path)

    def test_platform_providers_write_their_native_config(self):
        expect = {"render": "render/render.yaml", "flyio": "fly/api.fly.toml", "railway": "railway/api.railway.json", "heroku": "heroku/api/app.json",
                  "vercel": "vercel/api.vercel.json", "netlify": "netlify/netlify.toml", "cloudflare": "cloudflare/api.wrangler.toml",
                  "firebase": "firebase/firebase.json", "supabase": "supabase/config.toml", "fastly": "fastly/fastly.toml",
                  "denodeploy": "deno/api.deno.json", "databricks": "databricks/databricks.yml", "snowflake": "snowflake/setup.sql"}
        for provider, path in expect.items():
            with self.subTest(provider=provider):
                _, _, _, _, result = build(provider)
                self.assertIn(path, result["files"])

    def test_toml_and_json_outputs_parse(self):
        for provider in ("flyio", "netlify", "cloudflare", "fastly", "supabase", "railway", "vercel", "firebase", "heroku"):
            with self.subTest(provider=provider):
                _, _, _, _, result = build(provider)
                for path, text in result["files"].items():
                    if path.endswith(".toml"):
                        tomllib.loads(text)
                    elif path.endswith(".json"):
                        json.loads(text)

    def test_overlays_add_data_modules(self):
        _, _, _, _, result = build("render", "server", monorepo, also=("neon", "mongodbatlas"))
        self.assertIn("terraform-neon/main.tf", result["files"])
        self.assertIn("terraform-mongodbatlas/main.tf", result["files"])



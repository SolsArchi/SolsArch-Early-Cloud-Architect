class NoCloudBias(unittest.TestCase):
    def scores(self, builder):
        return {p: build(p, "server", builder)[4]["manifest"]["parity"]["score"] for p in MAJORS}

    def test_the_three_major_clouds_score_within_ten_points(self):
        for builder in (monorepo, single_app):
            with self.subTest(builder=builder.__name__):
                scores = self.scores(builder)
                self.assertLessEqual(max(scores.values()) - min(scores.values()), 12.0, scores)

    def test_every_provider_reports_every_capability_the_same_way(self):
        ids = [c[0] for c in iac_parity.CAPABILITIES]
        for provider in providers.hosting_ids():
            with self.subTest(provider=provider):
                rows = build(provider)[4]["manifest"]["parity"]["capabilities"]
                self.assertEqual([r["id"] for r in rows], ids)
                for r in rows:
                    self.assertIn(r["status"], ("implemented", "provider_managed", "gap", "not_applicable", "not_offered"))

    def test_a_gap_is_never_scored_as_met(self):
        for provider in ("digitalocean", "ibm", "scaleway"):
            parity = build(provider)[4]["manifest"]["parity"]
            met = sum(1 for r in parity["capabilities"] if r["status"] in ("implemented", "provider_managed"))
            self.assertEqual(met, parity["met"])

    def test_plan_engine_choices_do_not_depend_on_the_provider_name(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            monorepo(root)
            scan = ast_scanner.scan(root)
            cat = recommend.load_catalog()
            prof = dict(architect.PROFILE_DEFAULTS)
            keys = {p: tuple(d["key"] for d in recommend.build_plan(scan, cat, p, "server", [], prof)["decisions"]) for p in MAJORS}
            self.assertEqual(len(set(keys.values())), 1, keys)


class KubernetesOutput(unittest.TestCase):
    def test_manifests_are_hardened(self):
        _, _, _, _, result = build("linode")
        text = result["files"]["kubernetes/deployment-api.yaml"]
        for needle in ("runAsNonRoot: true", "readOnlyRootFilesystem: true", "allowPrivilegeEscalation: false", "livenessProbe", "readinessProbe", "limits:"):
            self.assertIn(needle, text)
        self.assertIn("default-deny", result["files"]["kubernetes/networkpolicy.yaml"])

    def test_yaml_parses(self):
        try:
            import yaml
        except ImportError:
            self.skipTest("PyYAML is not installed")
        for provider in ("linode", "vultr", "ovhcloud"):
            _, _, _, _, result = build(provider, "server", monorepo)
            for path, text in result["files"].items():
                if path.endswith((".yaml", ".yml")) and "helm/" not in path and "roles/" not in path and "group_vars" not in path:
                    list(yaml.safe_load_all(text))

    def test_helm_chart_is_included(self):
        _, _, _, _, result = build("vultr")
        self.assertTrue(any(p.startswith("helm/") and p.endswith("Chart.yaml") for p in result["files"]))


class DeployGuide(unittest.TestCase):
    def guide(self, provider, account, mode="server"):
        plan, design, prof, scan, result = build(provider, mode, monorepo, profile={"account_type": account})
        return deploy_guide.build(plan, design, prof, result["manifest"], result["files"])

    def test_every_provider_and_account_type_has_a_complete_guide(self):
        for account in ("free_trial", "free_tier", "pay_as_you_go", "standard"):
            for provider in providers.hosting_ids():
                with self.subTest(provider=provider, account=account):
                    text = self.guide(provider, account)
                    for heading in ("## Step 1.", "## Step 2.", "## Step 3.", "## Step 4.", "## Step 5", "## Step 6.", "## Step 8.", "## If something goes wrong"):
                        self.assertIn(heading, text)
                    self.assertIn(deploy_guide.ACCOUNT_LABELS[account], text)
                    self.assertNotIn("@@", text)

    def test_the_guide_never_quotes_a_price(self):
        import re
        for provider in ("aws", "render", "hetzner"):
            text = self.guide(provider, "free_trial")
            self.assertIsNone(re.search(r"[$€£]\s?\d", text), provider)

    def test_account_type_changes_the_advice(self):
        trial = self.guide("aws", "free_trial")
        paid = self.guide("aws", "standard")
        self.assertIn("date your trial ends", trial)
        self.assertNotIn("date your trial ends", paid)
        self.assertIn("separate account", paid)

    def test_terminal_and_console_paths_are_both_present(self):
        text = self.guide("aws", "pay_as_you_go")
        self.assertIn("terminal path", text)
        self.assertIn("by clicking in the console", text)

    def test_guide_data_covers_every_provider(self):
        data = deploy_guide.load()
        self.assertEqual([p for p in providers.hosting_ids() if p not in data["providers"]], [])


class ReferenceTools(unittest.TestCase):
    def test_knowledge_search_is_stable_and_finds_terraform_state(self):
        a = knowledge.search("terraform state locking remote backend", 3)
        b = knowledge.search("terraform state locking remote backend", 3)
        self.assertEqual(a, b)
        self.assertTrue(a)
        self.assertEqual(len(knowledge.chapters()), 16)

    def test_eol_check_flags_an_old_runtime(self):
        with tempfile.TemporaryDirectory() as t:
            write(t, "Dockerfile", "FROM node:16-alpine\n")
            found = eol_check.check(t)
            self.assertEqual([r["status"] for r in found["findings"]], ["end_of_life"])

    def test_design_review_reports_end_of_life(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            monorepo(root)
            write(root, "services/api/Dockerfile", "FROM python:3.8\nEXPOSE 8000\nUSER app\n")
            scan = ast_scanner.scan(root)
            plan = recommend.build_plan(scan, recommend.load_catalog(), "aws", "server", [], dict(architect.PROFILE_DEFAULTS))
            rules = {r["id"]: r for r in architect.review(root, scan, plan)["rules"]}
            self.assertEqual(rules["DR-12"]["status"], "violated")

    def test_mcp_sources_list_every_provider_dated(self):
        listing = mcp_sources.listing()
        self.assertGreaterEqual(len(listing["sources"]), 50)
        self.assertTrue(listing["checked"])
        self.assertTrue(mcp_sources.discover("hetzner")["registry_query"].startswith("https://registry.modelcontextprotocol.io"))



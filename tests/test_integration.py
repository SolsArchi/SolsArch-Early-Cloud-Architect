"""The merged pieces working together: scanner -> evidence bridge -> placement -> report -> verify -> zip."""
import json
import shutil
import zipfile
from pathlib import Path

import ast_scanner
import evidence_bridge
import helpers

FIXTURES = helpers.FIXTURES


def copy_fixture(name, tmp_path):
    target = tmp_path / name
    shutil.copytree(FIXTURES / name, target)
    return target


def test_generated_and_gitignored_dirs_are_skipped(tmp_path):
    helpers.write(tmp_path, "runs/a/main.tf", 'resource "aws_vpc" "v" {}\n')
    helpers.write(tmp_path, ".gitignore", "scratch/\n")
    helpers.write(tmp_path, "scratch/requirements.txt", "flask\n")
    result = ast_scanner.scan(tmp_path)
    assert result["infrastructure"]["terraform_resources"] == {}
    assert result["components"] == []


def test_new_frameworks_and_rust_sqlite_detected(tmp_path):
    helpers.write(tmp_path, "package.json", '{"dependencies": {"fastify": "4"}}')
    helpers.write(tmp_path, "Cargo.toml", '[dependencies]\naxum = "0.7"\nrusqlite = "0.31"\n')
    names = {c["name"] for c in ast_scanner.scan(tmp_path)["components"]}
    assert {"Fastify", "Axum", "SQLite"} <= names


def test_bridge_ids_are_sequential_and_stable():
    first = evidence_bridge.flatten(ast_scanner.scan(FIXTURES / "saas"))
    second = evidence_bridge.flatten(ast_scanner.scan(FIXTURES / "saas"))
    ids = [e["id"] for e in first["evidence"]]
    assert ids == ["E%03d" % (i + 1) for i in range(len(ids))]
    assert first == second


def test_bridge_never_carries_secret_values(tmp_path):
    helpers.write(tmp_path, "cfg.py", 'AWS_KEY = "%s"\n' % helpers.fake_aws_key())
    text = json.dumps(evidence_bridge.flatten(ast_scanner.scan(tmp_path)))
    assert helpers.fake_aws_key() not in text
    assert '"secret"' in text


def test_bridge_cli(tmp_path):
    scan_file = tmp_path / "scan.json"
    out_file = tmp_path / "out" / "evidence.json"
    scan_file.write_text(json.dumps(ast_scanner.scan(FIXTURES / "rag")), encoding="utf-8")
    assert evidence_bridge.main([str(scan_file), "--output", str(out_file)]) == 0
    assert json.loads(out_file.read_text(encoding="utf-8"))["evidence"]
    assert evidence_bridge.main([str(tmp_path / "missing.json")]) == 2


def test_full_pipeline_writes_verified_zip_with_html(tmp_path):
    repo = copy_fixture("rag", tmp_path)
    out = helpers.pipeline(str(repo))
    assert out["verification"] == "passed"
    names = set(zipfile.ZipFile(out["zip"]).namelist())
    assert {"report.html", "data/evidence.json", "data/placements.json", "solsarch-report.md",
            "diagrams/index.html"} <= names
    assert any(n.startswith("diagrams/") and n.endswith(".mmd") for n in names)
    assert "images/architecture-icons.svg" in names
    code, out = helpers.cli("verify", "--repo", repo)
    assert code == 0 and out["status"] == "ok"


def test_report_cites_evidence_ids_that_exist(tmp_path):
    repo = copy_fixture("saas", tmp_path)
    helpers.pipeline(str(repo))
    report = (repo / "docs" / "solsarch-report.md").read_text(encoding="utf-8")
    valid = {e["id"] for e in json.loads((repo / ".solsarch" / "evidence.json").read_text(encoding="utf-8"))["evidence"]}
    import re
    cited = set(re.findall(r"\bE\d{3,}\b", report))
    assert cited and cited <= valid


def test_verify_catches_invented_evidence_id(tmp_path):
    repo = copy_fixture("saas", tmp_path)
    helpers.pipeline(str(repo))
    report = repo / "docs" / "solsarch-report.md"
    report.write_text(report.read_text(encoding="utf-8") + "\nThe cache is justified by E999.\n", encoding="utf-8")
    code, out = helpers.cli("verify", "--repo", repo)
    assert code == 1 and out["status"] == "failed"
    assert any("E999" in e["message"] for e in out["errors"])


def test_finish_refuses_to_package_a_failed_report_unless_forced(tmp_path):
    repo = copy_fixture("saas", tmp_path)
    helpers.pipeline(str(repo))
    state = repo / ".solsarch" / "evidence.json"
    # Evidence regenerated by finish would hide the problem, so make the report itself bad via the narrative.
    narrative = tmp_path / "notes.md"
    narrative.write_text("Key AKIA" + "ABCDEFGHIJKLMNOP" + " was seen.\n", encoding="utf-8")
    code, out = helpers.cli("finish", "--repo", repo, "--narrative", narrative)
    assert code == 1 and out["step"] == "verify"
    code, out = helpers.cli("finish", "--repo", repo, "--narrative", narrative, "--force")
    assert code == 0 and out["verification"].startswith("failed")
    assert state.exists()


def test_evidence_command_requires_scan(tmp_path):
    code, out = helpers.cli("evidence", "--repo", tmp_path)
    assert code == 2 and out["status"] == "error"


def test_icon_dir_option_is_accepted(tmp_path):
    repo = copy_fixture("saas", tmp_path)
    icons = tmp_path / "icons"
    icons.mkdir()
    (icons / "database.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg"><circle r="4" id="custom-icon-marker"/></svg>', encoding="utf-8")
    code, out = helpers.cli("scan", "--repo", repo)
    assert code == 0
    code, out = helpers.cli("plan", "--repo", repo, "--cloud", "aws", "--compute", "server")
    assert code == 0
    code, out = helpers.cli("evidence", "--repo", repo, "--icon-dir", icons)
    assert code == 0 and out["icon_diagram"] is True
    svg = Path(repo / ".solsarch" / "architecture-icons.svg").read_text(encoding="utf-8")
    assert svg.startswith("<svg")
    assert "data:image/svg+xml;base64," in svg
